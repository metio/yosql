package wtf.metio.yosql.example.gradle.jdbc;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.MethodSource;
import wtf.metio.yosql.example.common.StatementShapes;
import wtf.metio.yosql.example.gradle.jdbc.persistence.CallcenterRepository;
import wtf.metio.yosql.example.gradle.jdbc.persistence.CompanyRepository;
import wtf.metio.yosql.example.gradle.jdbc.persistence.ItemRepository;
import wtf.metio.yosql.example.gradle.jdbc.persistence.PersonRepository;
import wtf.metio.yosql.example.gradle.jdbc.persistence.SchemaRepository;
import wtf.metio.yosql.example.gradle.jdbc.persistence.UserRepository;

import java.util.List;
import java.util.stream.Stream;

/**
 * Every shape of method the generator can write is written by the Gradle example too.
 *
 * <p>The same statements as the Maven example, generated by a different frontend. The Maven gate
 * never builds this one, so a Gradle plugin that stopped emitting a shape — a returning mode its
 * task configuration no longer passed on, a statement type it skipped — would leave that gate green
 * and the example running whatever was left.</p>
 *
 * <p>What counts as a shape is {@link StatementShapes}, shared with the Maven example so that the
 * two cannot disagree about the question while disagreeing about the answer.</p>
 */
@DisplayName("the generated example repositories")
class GeneratedMatrixTest {

    private static final List<Class<?>> REPOSITORIES = List.of(
            CallcenterRepository.class, CompanyRepository.class, ItemRepository.class,
            PersonRepository.class, SchemaRepository.class, UserRepository.class);

    static Stream<String> combinations() {
        return StatementShapes.combinations().stream();
    }

    @ParameterizedTest(name = "{0}")
    @MethodSource("combinations")
    @DisplayName("cover every shape a statement can take")
    void isCovered(final String combination) {
        final var covered = StatementShapes.coveredBy(REPOSITORIES);

        Assertions.assertTrue(covered.contains(combination),
                () -> "no example statement generates " + combination + " through Gradle, so "
                        + "nothing runs that method against a database.\ncovered: " + covered);
    }

}
