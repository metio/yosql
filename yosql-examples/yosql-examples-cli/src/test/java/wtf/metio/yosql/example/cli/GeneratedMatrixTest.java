package wtf.metio.yosql.example.cli;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.MethodSource;
import wtf.metio.yosql.example.cli.persistence.CallcenterRepository;
import wtf.metio.yosql.example.cli.persistence.CompanyRepository;
import wtf.metio.yosql.example.cli.persistence.ItemRepository;
import wtf.metio.yosql.example.cli.persistence.PersonRepository;
import wtf.metio.yosql.example.cli.persistence.SchemaRepository;
import wtf.metio.yosql.example.cli.persistence.UserRepository;
import wtf.metio.yosql.example.common.StatementShapes;

import java.util.List;
import java.util.stream.Stream;

/**
 * Every shape of method the generator can write is written by the CLI example too.
 *
 * <p>The same statements as the Maven, Gradle and Ant examples, generated by the fourth frontend —
 * and the one that also ships as a native binary, where a shape nobody compiles is a shape nobody
 * would find. A returning mode the command stopped passing on would leave this example running
 * whatever was left.</p>
 *
 * <p>What counts as a shape is {@link StatementShapes}, shared with the other examples so that they
 * cannot disagree about the question while disagreeing about the answer.</p>
 */
@DisplayName("the generated example repositories")
class GeneratedMatrixTest {

    private static final List<Class<?>> REPOSITORIES = List.of(
            CallcenterRepository.class, CompanyRepository.class, ItemRepository.class,
            PersonRepository.class, SchemaRepository.class, UserRepository.class);

    static Stream<String> combinations() {
        return StatementShapes.combinations().stream();
    }

    @ParameterizedTest(name = "{0}")
    @MethodSource("combinations")
    @DisplayName("cover every shape a statement can take")
    void isCovered(final String combination) {
        final var covered = StatementShapes.coveredBy(REPOSITORIES);

        Assertions.assertTrue(covered.contains(combination),
                () -> "no example statement generates " + combination + " through the CLI, so "
                        + "nothing runs that method against a database.\ncovered: " + covered);
    }

}
