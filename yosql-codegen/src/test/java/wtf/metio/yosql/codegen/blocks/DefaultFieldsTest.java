package wtf.metio.yosql.codegen.blocks;

import wtf.metio.yosql.codegen.YoSqlVersion;
import com.palantir.javapoet.TypeName;
import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

@DisplayName("DefaultFields")
class DefaultFieldsTest {

    private DefaultFields generator;

    @BeforeEach
    void setUp() {
        generator = new DefaultFields(BlocksObjectMother.annotationGenerator());
    }

    @Test
    @DisplayName("creates fields")
    void shouldCreateField() {
        Assertions.assertEquals("""
                @javax.annotation.processing.Generated(
                    value = "wtf.metio.yosql",
                    comments = "generated by YoSQL ${version} - do not modify, this file is rewritten on every build"
                )
                private final java.lang.String test;
                """.replace("${version}", YoSqlVersion.VERSION), generator.field(String.class, "test").toString());
    }

    @Test
    @DisplayName("creates fields for TypeNames")
    void shouldCreateFieldWithTypeName() {
        Assertions.assertEquals("""
                @javax.annotation.processing.Generated(
                    value = "wtf.metio.yosql",
                    comments = "generated by YoSQL ${version} - do not modify, this file is rewritten on every build"
                )
                private final boolean test;
                """.replace("${version}", YoSqlVersion.VERSION), generator.field(TypeName.BOOLEAN, "test").toString());
    }

}
